RESAMPLE_GUIDE_TITLE = "Understanding Sample Rates"

RESAMPLE_GUIDE_TEXT = (
    "HOW SAMPLE RATE WORKS\n"
    "\n"
    "Digital audio is a series of snapshots (samples) of the sound wave.\n"
    "The sample rate is how many snapshots are taken per second, so\n"
    "48,000 Hz means 48,000 samples for every second of audio.\n"
    "\n"
    "Resampling recalculates the file at a new rate. The duration and\n"
    "pitch stay the same; only the number of samples changes.\n"
    "\n"
    "\n"
    "THE KEY RULE: HALF THE SAMPLE RATE\n"
    "\n"
    "A file can only contain frequencies up to half its sample rate\n"
    "(the Nyquist limit). In practice the usable range ends slightly\n"
    "below that, because the resampler filters out content near the\n"
    "limit to prevent distortion (aliasing).\n"
    "\n"
    "\n"
    "COMMON RATES\n"
    "\n"
    "  Sample rate   Keeps up to   Typical use\n"
    "  -----------   -----------   ------------------------------\n"
    "  2,000 Hz      1 kHz         Baleen whale calls (low freq)\n"
    "  8,000 Hz      4 kHz         Telephone speech\n"
    "  16,000 Hz     8 kHz         Speech, speech recognition\n"
    "  44,100 Hz     ~22 kHz       CD audio, full human hearing\n"
    "  48,000 Hz     24 kHz        Video and professional audio\n"
    "  96,000 Hz     48 kHz        High-resolution recording\n"
    "  192,000 Hz    96 kHz        Dolphin whistles, bat calls\n"
    "  384,000 Hz    192 kHz       Echolocation clicks (porpoise)\n"
    "\n"
    "\n"
    "DOWNSAMPLING (lower rate)\n"
    "\n"
    "  - Permanently removes everything above half the new rate.\n"
    "    Resampling to 16,000 Hz discards all sound above 8 kHz,\n"
    "    including clicks or vessel noise you may want to analyze.\n"
    "  - File size shrinks in proportion: half the rate is roughly\n"
    "    half the size.\n"
    "  - Great for low-frequency work: if you only need sounds below\n"
    "    1 kHz, a 2,000 Hz file is far smaller and faster to process.\n"
    "\n"
    "\n"
    "UPSAMPLING (higher rate)\n"
    "\n"
    "  - Adds no new detail. Frequencies that weren't captured in the\n"
    "    original recording can't be recovered.\n"
    "  - Makes files larger. Mainly useful when another tool requires\n"
    "    a specific rate or when matching files to a common rate.\n"
    "\n"
    "\n"
    "TIP\n"
    "\n"
    "Before downsampling, check the highest frequency you care about\n"
    "and choose a rate at least a bit more than twice that value. Keep\n"
    "your original files, since removed frequencies can't be restored.\n"
)


GAIN_GUIDE_TITLE = "Understanding Gain"

GAIN_GUIDE_TEXT = (
    "HOW GAIN WORKS\n"
    "\n"
    "Gain multiplies every sample in the file by the same number. The\n"
    "waveform keeps its shape; it just gets taller (louder) or shorter\n"
    "(quieter). The dB value you enter is converted to that multiplier:\n"
    "\n"
    "    multiplier = 10 ^ (gain dB / 20)\n"
    "\n"
    "\n"
    "COMMON VALUES\n"
    "\n"
    "  Gain     Multiplier   Power    How it sounds\n"
    "  -------  ----------   ------   ---------------------------\n"
    "  +3 dB    x 1.41       2x       Noticeably louder\n"
    "  +6 dB    x 2.00       4x       Clearly louder\n"
    "  +10 dB   x 3.16       10x      About twice as loud\n"
    "  -3 dB    x 0.71       1/2      Noticeably quieter\n"
    "  -6 dB    x 0.50       1/4      Clearly quieter\n"
    "  -10 dB   x 0.32       1/10     About half as loud\n"
    "\n"
    "\n"
    "RULES OF THUMB\n"
    "\n"
    "  - Every +6 dB doubles the sample values; every -6 dB halves them.\n"
    "  - Decibels add while multipliers multiply: +3 dB then another\n"
    "    +3 dB = +6 dB (1.41 x 1.41 = 2).\n"
    "  - Your ears hear loudness logarithmically: 1 dB is barely\n"
    "    noticeable, 3 dB is a clear step, and 10 dB sounds roughly\n"
    "    twice as loud.\n"
    "\n"
    "\n"
    "CLIPPING\n"
    "\n"
    "Samples in .wav and .flac files can't go beyond full scale (1.0).\n"
    "A file whose loudest peak is 0.5 sits at -6 dBFS (dB relative to\n"
    "full scale), so it can take up to +6 dB of gain. Adding +10 dB\n"
    "would push that peak to 1.58, so the tops get flattened at 1.0\n"
    "(clipped), which causes distortion. EZ AudioMate lists any files\n"
    "that clipped when processing finishes. Negative gain never clips.\n"
    "\n"
    "\n"
    "MEASURING LEVELS (AUDIO INFO TAB)\n"
    "\n"
    "Gain is a change you apply, not a property of a file. What you\n"
    "can measure is a file's level, which tells you how much gain it\n"
    "can take:\n"
    "\n"
    "  Peak level   Loudest single sample, in dBFS. 0 dBFS is the\n"
    "               maximum; -6 dBFS is half of full scale.\n"
    "  RMS level    Average level over the whole file. Closer to how\n"
    "               loud it sounds; always lower than the peak.\n"
    "  Headroom     Distance from the peak to 0 dBFS. This is the\n"
    "               most gain you can add before clipping.\n"
    "\n"
    "Example: a file peaking at -9.5 dBFS has 9.5 dB of headroom, so\n"
    "+6 dB is safe but +10 dB would clip.\n"
    "\n"
    "\n"
    "CALIBRATED RECORDINGS\n"
    "\n"
    "If your sample values map to real sound levels (for example,\n"
    "calibrated hydrophone data), applying gain shifts those levels by\n"
    "the same number of dB. Account for it in your calibration, or keep\n"
    "the original files for analysis.\n"
)
